import pytest
from app.schemas.business import BusinessOnboardingRequest, DaySchedule
from app.services import glm, seed_generator
from app.services.change_detector import detect_change

BUSINESS = BusinessOnboardingRequest(
    business_name="Sok's Café",
    business_type="cafe",
    business_description="Iced coffee and fresh pastries in Prek Eng.",
    email="hello@example.com",
    opening_hours=[DaySchedule(day="Monday", opens="7:00 AM", closes="5:00 PM"), DaySchedule(day="Sunday", is_open=False)],
)


def test_literal_escapes_quotes_and_control_characters():
    assert seed_generator.literal("O'Brien\x00; DROP TABLE products; --") == "'O''Brien; DROP TABLE products; --'"
    assert seed_generator.literal(None) == "NULL"
    assert seed_generator.literal(True) == "TRUE"
    assert seed_generator.literal(3) == "3"


def test_clean_products_enforces_limits_and_drops_bad_items():
    items = [{"name": "Latte", "price": "$3", "description": "x" * 5000}, {"name": "latte"}, {"price": "$1"}, "junk",
             {"name": "  ", "price": "$2"}, {"name": "Croissant", "category": ""}]
    cleaned = seed_generator.clean_products(items)
    assert [p["name"] for p in cleaned] == ["Latte", "Croissant"]
    assert len(cleaned[0]["description"]) == seed_generator.LIMITS["description"]
    assert cleaned[1]["category"] == "General"
    assert len(seed_generator.clean_products([{"name": f"P{i}"} for i in range(50)])) == seed_generator.MAX_PRODUCTS


def test_render_seed_sql_inserts_profile_and_products_into_empty_tables_only():
    products = seed_generator.clean_products([{"name": "Iced Latte", "price": "$3.50", "description": "Cold."}])
    sql = seed_generator.render_seed_sql(seed_generator.build_seed(products, BUSINESS))
    assert sql.startswith("-- Seed data generated by the WebBlock AI harness.")
    # The harness runs it inside its own transaction (site_catalog.prepare_site), so the script has none.
    assert "SET LOCAL standard_conforming_strings = on;" in sql and "BEGIN;" not in sql and "COMMIT;" not in sql
    website = "current_setting('webblock.website_id')::uuid"
    assert f"SELECT {website}, 'Sok''s Café', " in sql  # the business type belongs to catalog.websites
    assert "'hello@example.com'" in sql and "NULL" in sql  # phone_number is not set
    assert '"day": "Monday", "isOpen": true, "opens": "7:00 AM"' in sql and "::jsonb" in sql
    assert "INSERT INTO catalog.business_profiles" in sql and "ON CONFLICT (website_id) DO NOTHING;" in sql
    assert "('Iced Latte', 'Cold.', 3.50::numeric(12,2), 'general', 0)" in sql
    assert f"catalog.item_schema_id({website})" in sql
    assert f"WHERE NOT EXISTS (SELECT 1 FROM catalog.products p WHERE p.website_id = {website});" in sql


