def test_propose_products_uses_glm_and_falls_back_to_templates(monkeypatch):
    monkeypatch.setattr(glm, "is_configured", lambda: True)
    monkeypatch.setattr(glm, "request_seed_products", lambda business: {"products": [{"name": "Num Pang", "price": "$2"}]})
    products, source = seed_generator.propose_products(BUSINESS, use_glm=True)
    assert source == "glm" and products[0]["name"] == "Num Pang"

    products, source = seed_generator.propose_products(BUSINESS, use_glm=False)
    assert source == "template" and products == seed_generator.template_products(BUSINESS)

    def fail(business):
        raise glm.GLMError("timeout")
    monkeypatch.setattr(glm, "request_seed_products", fail)
    assert seed_generator.propose_products(BUSINESS, use_glm=True)[1] == "template"
    monkeypatch.setattr(glm, "request_seed_products", lambda business: {"products": [{"price": "$1"}]})
    assert seed_generator.propose_products(BUSINESS, use_glm=True)[1] == "template"


def test_products_from_input_reads_every_product_cards_block():
    page = lambda path, order, names: {"path": path, "sort_order": order, "puck_tree": {"content": [  # noqa: E731
        {"type": "ProductCards", "props": {"products": [{"name": n} for n in names]}}, {"type": "Hero", "props": {}}]}}
    captured = {"pages": [page("/shop", 1, ["Mug", "Bowl"]), page("/", 0, ["Vase"])]}
    assert [p["name"] for p in seed_generator.products_from_input(captured)] == ["Vase", "Mug", "Bowl"]


def test_seed_change_is_a_content_change():
    old = {"pages": [], "drizzle_schema": None, "seed": {"products": [{"name": "A"}]}}
    diff = detect_change(old, {**old, "seed": {"products": [{"name": "B"}]}})
    assert diff["changed"] and diff["strategy"] == "PUCK_JSON"
    assert not detect_change(old, {**old, "seed": None})["changed"]  # None keeps the baseline's seed


def test_user_text_cannot_end_a_comment_in_the_seed():
    """A carriage return ends a SQL -- comment (security review)."""
    evil = BusinessOnboardingRequest(business_name="Acme\rCREATE TABLE pwned AS SELECT 1;-- */ console.log(1); /*",
                                     business_type="cafe */ process.exit(1) /*\r\nx",
                                     business_description="Coffee and more.")
    sql = seed_generator.render_seed_sql(seed_generator.build_seed([], evil))
    comments = [line for line in sql.splitlines() if line.startswith("--")]
    assert all("Acme" not in line and "pwned" not in line for line in comments)
    assert "\r" not in sql.replace("''", "")  # the name only appears inside a literal, and \r was normalized
    assert "'Acme\nCREATE TABLE pwned AS SELECT 1;-- */ console.log(1); /*'" in sql


def test_stored_business_profile_is_revalidated():
    seed = seed_generator.build_seed([], BUSINESS)
