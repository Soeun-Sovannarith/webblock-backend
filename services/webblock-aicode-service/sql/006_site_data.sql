-- Row-level security on every data table: a session sees and writes only its own project's rows.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['business_profiles','products','portal_revoked_sessions','contact_inquiries',
                           'reservations','bookings','testimonials','orders'] LOOP
    EXECUTE format('ALTER TABLE site_data.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE site_data.%I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON site_data.%I', t);
    EXECUTE format('CREATE POLICY tenant_isolation ON site_data.%I USING (project_id = (SELECT site_data.current_project_id())) '
                   'WITH CHECK (project_id = (SELECT site_data.current_project_id()))', t);
  END LOOP;
END $$;

-- The sites' role. Created here when the migration role may create roles; otherwise a DBA creates it
-- (README section 9.7) and runs the grants below.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'webblock_site') THEN
    CREATE ROLE webblock_site NOLOGIN;
  END IF;
EXCEPTION WHEN insufficient_privilege THEN
  RAISE NOTICE 'Cannot create role webblock_site here; create it as a DBA and re-run the grants in sql/006_site_data.sql.';
END $$;

DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'webblock_site') THEN
    REVOKE ALL ON site_data.tenants FROM webblock_site;
    GRANT USAGE ON SCHEMA site_data TO webblock_site;
    GRANT SELECT, INSERT, UPDATE, DELETE ON site_data.business_profiles, site_data.products, site_data.portal_revoked_sessions,
      site_data.contact_inquiries, site_data.reservations, site_data.bookings, site_data.testimonials, site_data.orders
      TO webblock_site;
    GRANT EXECUTE ON FUNCTION site_data.current_project_id() TO webblock_site;
  END IF;
END $$;
