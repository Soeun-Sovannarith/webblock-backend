-- Generated sites' own data (schema site_data): every site keeps its catalog, business profile, portal sessions and
-- business-type tables here, in shared tables with a project_id column, instead of in a database of its own.
-- Row-level security keeps the sites apart: a site connects as the role webblock_site with its tenant token in the
-- session setting webblock.site_token (lib/db.ts), site_data.current_project_id() turns the token into its
-- project_id, and every policy admits only that project's rows. Inserts fill project_id from the same function, so
-- the site's SQL never names it. FORCE makes the policies apply to the owner (ai_codegen) and its members (dev_svr)
-- too; only superusers bypass them. project_id references the Project service and is a plain uuid in tenants;
-- the data tables reference tenants, and (project_id, id) is unique in each so a later foreign key between two
-- site tables can include project_id and never point at another project's row.
-- Idempotent: IF NOT EXISTS, CREATE OR REPLACE, DROP POLICY IF EXISTS before CREATE POLICY; the role is created only
-- when missing and when the migration role may create roles, and the grants only when the role exists.
CREATE SCHEMA IF NOT EXISTS site_data;

-- One row per site; the harness writes it (site_data.ensure_tenant). Sites cannot read it.
CREATE TABLE IF NOT EXISTS site_data.tenants (
 project_id uuid PRIMARY KEY,
 token_sha256 bytea NOT NULL UNIQUE,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);

-- The project of the current session, or NULL without a valid token. SECURITY DEFINER so that sites can resolve their
-- own token without reading tenants.
CREATE OR REPLACE FUNCTION site_data.current_project_id() RETURNS uuid
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
  SELECT t.project_id FROM site_data.tenants t
  WHERE t.token_sha256 = sha256(convert_to(current_setting('webblock.site_token', true), 'UTF8'))
$$;

