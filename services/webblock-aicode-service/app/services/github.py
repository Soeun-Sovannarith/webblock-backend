import re
from dataclasses import dataclass
from typing import Any
import httpx
from app.core.config import settings

class GitHubError(Exception):
    pass

@dataclass
class PushResult:
    status: str  # SUCCEEDED | SKIPPED
    commit_sha: str | None = None
    repository_id: int | None = None
    full_name: str | None = None  # "<owner>/<repo>", stored as projects.repository_full_name
    message: str = ""

def is_configured() -> bool:
    return bool(settings.github_token)

def parse_repo_url(url: str) -> tuple[str, str] | None:
    m = re.match(r"^(?:https://github\.com/|git@github\.com:)([^/\s]+)/([^/\s]+?)(?:\.git)?/?$", url.strip())
    return (m.group(1), m.group(2)) if m else None

def repo_url(full_name: str | None) -> str | None:
    return f"https://github.com/{full_name}" if full_name else None

def slugify(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return slug[:60] or "site"

class GitHubClient:
    def __init__(self, token: str, api_url: str):
        self.http = httpx.Client(base_url=api_url.rstrip("/"), timeout=settings.request_timeout_seconds, headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        })

    def close(self) -> None:
        self.http.close()

    def _req(self, method: str, path: str, ok: tuple[int, ...] = (200, 201), **kw: Any) -> httpx.Response:
        try:
            resp = self.http.request(method, path, **kw)
        except httpx.HTTPError as e:
            raise GitHubError(f"{method} {path} failed: {e}") from e
        if resp.status_code not in ok:
            raise GitHubError(f"{method} {path} returned HTTP {resp.status_code}: {resp.text[:500]}")
        return resp

    def ensure_repo(self, owner: str, name: str) -> int:
        """Return the repository id, creating the repository if it does not exist."""
        resp = self._req("GET", f"/repos/{owner}/{name}", ok=(200, 404))
        if resp.status_code == 200:
            return resp.json()["id"]
        login = self._req("GET", "/user").json()["login"]
        path = "/user/repos" if login.lower() == owner.lower() else f"/orgs/{owner}/repos"
        body = {"name": name, "private": settings.github_private_repos, "auto_init": True,
                "description": "Generated by WebBlock"}
        return self._req("POST", path, json=body).json()["id"]

    def _branch_sha(self, owner: str, name: str, branch: str) -> str | None:
        resp = self._req("GET", f"/repos/{owner}/{name}/git/ref/heads/{branch}", ok=(200, 404, 409))
        return resp.json()["object"]["sha"] if resp.status_code == 200 else None

    def push_snapshot(self, owner: str, name: str, branch: str, files: dict[str, str], message: str) -> str:
        """Commit files as the complete tree of `branch` (files absent from the snapshot are removed)."""
        parent = self._branch_sha(owner, name, branch)
        branch_exists = parent is not None
        if not branch_exists:
            # Branch missing: base it on the repo's default branch (e.g. an existing repo using "master").
            default = self._req("GET", f"/repos/{owner}/{name}").json().get("default_branch")
            if default and default != branch:
                parent = self._branch_sha(owner, name, default)
        if parent is None:
            # Empty repository: the Git Data API needs at least one commit, so seed one via the contents API.
            self._req("PUT", f"/repos/{owner}/{name}/contents/.webblock", ok=(200, 201, 422), json={
                "message": "Initialize repository", "content": "V2ViQmxvY2sK", "branch": branch})
            parent = self._branch_sha(owner, name, branch)
            branch_exists = parent is not None
        tree = [{"path": p, "mode": "100644", "type": "blob", "content": c} for p, c in sorted(files.items())]
        tree_sha = self._req("POST", f"/repos/{owner}/{name}/git/trees", json={"tree": tree}).json()["sha"]
        commit = self._req("POST", f"/repos/{owner}/{name}/git/commits", json={
            "message": message, "tree": tree_sha, "parents": [parent] if parent else []}).json()["sha"]
        if branch_exists:
            self._req("PATCH", f"/repos/{owner}/{name}/git/refs/heads/{branch}", json={"sha": commit, "force": False})
        else:
            self._req("POST", f"/repos/{owner}/{name}/git/refs", json={"ref": f"refs/heads/{branch}", "sha": commit})
        return commit

def push(project: dict[str, Any], files: dict[str, str], message: str) -> PushResult:
    if not is_configured():
        return PushResult("SKIPPED", message="GitHub is not configured (set GITHUB_TOKEN).")
    full_name = project.get("repository_full_name")
    if full_name:
        owner, name = full_name.split("/", 1)
    elif settings.github_owner:
        owner, name = settings.github_owner, f"{slugify(project['name'])}-{str(project['project_id'])[:8]}"
    else:
        return PushResult("SKIPPED", message="Project has no repository and GITHUB_OWNER is not set.")
    client = GitHubClient(settings.github_token, settings.github_api_url)
    try:
        repo_id = client.ensure_repo(owner, name)
        sha = client.push_snapshot(owner, name, settings.git_branch, files, message)
        return PushResult("SUCCEEDED", sha, repo_id, f"{owner}/{name}", f"Pushed {sha[:7]} to {owner}/{name}@{settings.git_branch}")
    finally:
        client.close()
