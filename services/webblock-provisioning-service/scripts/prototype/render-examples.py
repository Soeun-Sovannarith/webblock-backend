"""Write the readable example manifests in deploy/prototype/manifests/ from the worker's renderer.

Decision 0014 section 20: ``src/provisioning/infrastructure/kubernetes/render.py`` is the only
source of the per-site and tenant manifests. This script calls it with fixed example values and
writes one YAML file per object group, for people to read and for ``proto-smoke``:

    tenant.yaml          Namespace wb-<projectId>, ResourceQuota, LimitRange, the ReferenceGrant in
                         webblock-offline, the worker's RoleBinding (bootstrap's order), and
                         access_setup's Secret catalog-runtime with placeholder values
    release.yaml         Deployment and Service rel-<releaseId> (command number 1)
    route-release.yaml   HTTPRoute route-<projectId> to rel-<releaseId> (command number 1)
    route-offline.yaml   HTTPRoute route-<projectId> to the offline page (command number 2)
    preview.yaml         HTTPRoute preview-<projectId> to rel-<releaseId> (command number 1)

``tests/unit/test_manifest_examples_drift.py`` fails when a committed file differs from this
script's output, so the files are never edited by hand: change the renderer, then run

    .venv/bin/python scripts/prototype/render-examples.py

The example values (the defaults below) are those of the prototype stack: the registry
``webblock-proto-registry.test:5000``, the site domain ``sites.webblock.test``, the worker's site
settings of ``scripts/prototype/run-provisioning.sh`` (100 millicores, 256 MiB, a 60 s progress
deadline below the 150 s readiness deadline, the offline page on port 8080) and its tenant quota.
The project, release, sub-domain, image digest, preview token and Secret values are examples, never
real ones. The site's host is ``<subdomain>.<site domain>`` (decision 0023 G18) and the preview's
``<subdomain>-preview.<site domain>`` (FR-20); the namespace carries the sub-domain
label the route policy checks (decision 0023 G18a). ``--project-id``, ``--release-id``,
``--subdomain`` and ``--image`` render the same files for other values (for example a smoke
test's), and ``--out`` writes them elsewhere; ``--check`` writes nothing and exits 1
when the files in ``--out`` differ from the output.

The renderer imports the Kubernetes client library, which fixes its default kubeconfig path from
``$KUBECONFIG`` when imported; ``KUBECONFIG`` is set to a path that never exists first. Nothing here
loads a kubeconfig or contacts a cluster.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Any
from uuid import UUID

os.environ["KUBECONFIG"] = "/nonexistent/webblock-render-examples-never-reads-a-kubeconfig"

import yaml

from provisioning.core.application.ports.site_cluster import (
    ReleaseWorkload,
    RouteTarget,
    RouteTargetKind,
)
from provisioning.core.application.routing.background.routing import preview_hostname
from provisioning.infrastructure.kubernetes.render import (
    SiteSettings,
    TenantSettings,
    render_deployment,
    render_limit_range,
    render_namespace,
    render_preview_route,
    render_reference_grant,
    render_resource_quota,
    render_route,
    render_runtime_secret,
    render_service,
    render_worker_role_binding,
)

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "deploy" / "prototype" / "manifests"

PROJECT_ID = UUID("11111111-1111-4111-8111-111111111111")
RELEASE_ID = UUID("22222222-2222-4222-8222-222222222222")
REGISTRY = "webblock-proto-registry.test:5000"
DIGEST = "sha256:" + "0" * 64
SITE_DOMAIN = "sites.webblock.test"
SUBDOMAIN = "example-shop"
PREVIEW_TOKEN = "example-preview-token-never-a-real-one-0123456789"  # noqa: S105 - an example
SITE = SiteSettings(
    cpu_millicores=100,
    memory_mib=256,
    progress_deadline_seconds=60,
    readiness_deadline_seconds=150,
    offline_service_port=8080,
)
TENANT = TenantSettings(
    quota_cpu="3",
    quota_memory="3Gi",
    quota_pods=10,
    container_max_cpu="1",
    container_max_memory="1Gi",
)
RELEASE_COMMAND = 1
OFFLINE_COMMAND = 2

GENERATED = (
    "# Generated by scripts/prototype/render-examples.py from\n"
    "# src/provisioning/infrastructure/kubernetes/render.py (decision 0014 section 20).\n"
    "# Do not edit: tests/unit/test_manifest_examples_drift.py fails when this file differs\n"
    "# from the renderer's output.\n"
)


def example_image(project_id: UUID) -> str:
    return f"{REGISTRY}/webblock/sites/{project_id}@{DIGEST}"


def secret_values(project_id: UUID) -> dict[str, str]:
    """Placeholders: access_setup writes the real values, which never appear in a file."""
    return {
        "PGHOST": "webblock-catalog-db",
        "PGPORT": "5432",
        "PGDATABASE": "catalog",
        "PGUSER": f"site_{project_id.hex}",
        "PGPASSWORD": "example-placeholder-not-a-password",
        "PGSSLMODE": "disable",
    }


def documents(
    project_id: UUID, release_id: UUID, image: str, subdomain: str
) -> dict[str, tuple[str, list[Any]]]:
    """File name to (description, objects), from the renderer only."""
    workload = ReleaseWorkload(project_id, release_id, image, RELEASE_COMMAND)
    hostnames = (f"{subdomain}.{SITE_DOMAIN}",)
    to_release = RouteTarget(RouteTargetKind.RELEASE, release_id)
    return {
        "tenant.yaml": (
            f"The tenant of project {project_id},\n"
            "applied by the tenant-bootstrap identity in this order (the worker's RoleBinding\n"
            "last), and access_setup's Secret catalog-runtime with placeholder values.",
            [
                render_namespace(project_id, subdomain=subdomain, catalog_secret=None),
                render_resource_quota(project_id, TENANT),
                render_limit_range(project_id, TENANT),
                render_reference_grant(project_id),
                render_worker_role_binding(project_id),
                render_runtime_secret(project_id, secret_values(project_id)),
            ],
        ),
        "release.yaml": (
            f"Release {release_id}\nof project {project_id},\n"
            f"command number {RELEASE_COMMAND}, applied by the release worker. Image:\n{image}",
            [render_deployment(workload, SITE), render_service(workload)],
        ),
        "route-release.yaml": (
            f"The site's route to release {release_id}, command number {RELEASE_COMMAND}.",
            [
                render_route(
                    project_id,
                    to_release,
                    hostnames,
                    RELEASE_COMMAND,
                    SITE,
                    site_domain=SITE_DOMAIN,
                    subdomain=subdomain,
                )
            ],
        ),
        "route-offline.yaml": (
            f"The site's route to the offline page, command number {OFFLINE_COMMAND}.",
            [
                render_route(
                    project_id,
                    RouteTarget(RouteTargetKind.OFFLINE),
                    hostnames,
                    OFFLINE_COMMAND,
                    SITE,
                    site_domain=SITE_DOMAIN,
                    subdomain=subdomain,
                )
            ],
        ),
        "preview.yaml": (
            f"The preview route to release {release_id}, command number {RELEASE_COMMAND}; the\n"
            "token is the project's HMAC of an example secret (the worker's secret is\n"
            "PREVIEW_PROBE_TOKEN, never written to a file; decision 0023 G18c).",
            [
                render_preview_route(
                    project_id,
                    release_id,
                    preview_hostname(subdomain, SITE_DOMAIN),
                    RELEASE_COMMAND,
                    preview_secret=PREVIEW_TOKEN,
                    site_domain=SITE_DOMAIN,
                    subdomain=subdomain,
                )
            ],
        ),
    }


def render_files(
    project_id: UUID, release_id: UUID, image: str, subdomain: str = SUBDOMAIN
) -> dict[str, str]:
    """File name to its full text."""
    files: dict[str, str] = {}
    for name, (description, objects) in documents(project_id, release_id, image, subdomain).items():
        header = GENERATED + "".join(f"# {line}\n" for line in description.splitlines())
        body = "---\n".join(
            yaml.safe_dump(obj, sort_keys=False, default_flow_style=False) for obj in objects
        )
        files[name] = header + body
    return files


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument(
        "--out", type=Path, default=OUT, help="the folder to write (default: %(default)s)"
    )
    parser.add_argument("--project-id", type=UUID, default=PROJECT_ID)
    parser.add_argument("--release-id", type=UUID, default=RELEASE_ID)
    parser.add_argument("--subdomain", default=SUBDOMAIN, help="the site's DNS label")
    parser.add_argument("--image", help="<registry>/webblock/sites/<projectId>@sha256:<digest>")
    parser.add_argument("--check", action="store_true", help="compare only; exit 1 on a difference")
    args = parser.parse_args(argv)
    image = args.image or example_image(args.project_id)
    files = render_files(args.project_id, args.release_id, image, args.subdomain)
    if args.check:
        stale = [n for n, text in files.items() if _read(args.out / n) != text]
        for name in stale:
            print(f"{args.out / name} differs from the renderer's output", file=sys.stderr)
        return 1 if stale else 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (args.out / name).write_text(text)
    return 0


def _read(path: Path) -> str | None:
    return path.read_text() if path.is_file() else None


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
